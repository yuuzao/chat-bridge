package httpserver

import (
	"bytes"
	"encoding/json"
	"errors"
	"io"
	"mime"
	"mime/multipart"
	"net/http"
	"strings"
	"unicode/utf8"

	"chat_bridge/internal/taskstore"
)

type inboundKind int

const (
	inboundCreate inboundKind = iota + 1
	inboundWebhook
)

type inboundFile struct {
	name string
	mime string
	data []byte
}

type inbound struct {
	authToken        string
	authPresent      bool
	requestID        string
	requestIDPresent bool
	content          string
	contentPresent   bool
	file             *inboundFile
}

func (s *Server) readInbound(w http.ResponseWriter, r *http.Request) (inbound, error) {
	if r.Body == nil {
		return inbound{}, statusErr(http.StatusBadRequest, "missing request body")
	}
	r.Body = http.MaxBytesReader(w, r.Body, s.cfg.MaxBodyBytes)
	defer func() {
		if err := r.Body.Close(); err != nil {
			s.log.Warn("close request body", "path", r.URL.Path, "error", err.Error())
		}
	}()
	mediaType, _, err := mime.ParseMediaType(r.Header.Get("Content-Type"))
	if err != nil {
		return inbound{}, statusErr(http.StatusUnsupportedMediaType, "unsupported content type")
	}
	switch mediaType {
	case "application/json":
		return readJSON(r)
	case "multipart/form-data":
		return readMultipart(r)
	default:
		return inbound{}, statusErr(http.StatusUnsupportedMediaType, "unsupported content type")
	}
}

func validateInbound(kind inboundKind, in inbound) error {
	switch kind {
	case inboundCreate:
		if in.requestIDPresent {
			return statusErr(http.StatusBadRequest, "request_id is generated by the server")
		}
	case inboundWebhook:
		if !in.requestIDPresent || in.requestID == "" {
			return statusErr(http.StatusBadRequest, "missing request_id")
		}
		if !taskstore.ValidID(in.requestID) {
			return statusErr(http.StatusBadRequest, "invalid request_id")
		}
	default:
		return errors.New("inbound kind is required")
	}
	if !in.contentPresent {
		return statusErr(http.StatusBadRequest, "missing content")
	}
	if !utf8.ValidString(in.content) {
		return statusErr(http.StatusBadRequest, "content must be utf-8")
	}
	return nil
}

func readJSON(r *http.Request) (inbound, error) {
	data, err := io.ReadAll(r.Body)
	if err != nil {
		if tooLarge(err) {
			return inbound{}, statusErr(http.StatusRequestEntityTooLarge, "request body too large")
		}
		return inbound{}, statusErrCause(http.StatusBadRequest, "read request body", err)
	}
	if len(bytes.TrimSpace(data)) == 0 {
		return inbound{}, statusErr(http.StatusBadRequest, "missing request body")
	}
	if err := rejectDuplicateJSONKeys(data); err != nil {
		var httpErr *statusError
		if errors.As(err, &httpErr) {
			return inbound{}, err
		}
		return inbound{}, statusErrCause(http.StatusBadRequest, "invalid json", err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	var obj map[string]json.RawMessage
	if err := dec.Decode(&obj); err != nil {
		return inbound{}, statusErrCause(http.StatusBadRequest, "invalid json", err)
	}
	if err := dec.Decode(&struct{}{}); !errors.Is(err, io.EOF) {
		return inbound{}, statusErr(http.StatusBadRequest, "invalid json")
	}
	allowed := map[string]struct{}{
		"auth_token": {},
		"request_id": {},
		"content":    {},
	}
	for key := range obj {
		if _, ok := allowed[key]; !ok {
			return inbound{}, statusErr(http.StatusBadRequest, "unknown field")
		}
	}
	var in inbound
	var fieldErr error
	in.authToken, in.authPresent, fieldErr = jsonString(obj, "auth_token")
	if fieldErr != nil {
		return inbound{}, fieldErr
	}
	in.requestID, in.requestIDPresent, fieldErr = jsonString(obj, "request_id")
	if fieldErr != nil {
		return inbound{}, fieldErr
	}
	in.content, in.contentPresent, fieldErr = jsonString(obj, "content")
	if fieldErr != nil {
		return inbound{}, fieldErr
	}
	return in, nil
}

func rejectDuplicateJSONKeys(data []byte) error {
	dec := json.NewDecoder(bytes.NewReader(data))
	token, err := dec.Token()
	if err != nil {
		return err
	}
	delim, ok := token.(json.Delim)
	if !ok || delim != '{' {
		return errors.New("json object required")
	}
	seen := map[string]struct{}{}
	for dec.More() {
		keyToken, err := dec.Token()
		if err != nil {
			return err
		}
		key, ok := keyToken.(string)
		if !ok {
			return errors.New("json key must be a string")
		}
		if _, exists := seen[key]; exists {
			return statusErr(http.StatusBadRequest, "duplicate field")
		}
		seen[key] = struct{}{}
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			return err
		}
	}
	token, err = dec.Token()
	if err != nil {
		return err
	}
	delim, ok = token.(json.Delim)
	if !ok || delim != '}' {
		return errors.New("json object required")
	}
	if err := dec.Decode(&struct{}{}); !errors.Is(err, io.EOF) {
		return errors.New("trailing json")
	}
	return nil
}

func jsonString(obj map[string]json.RawMessage, key string) (string, bool, error) {
	raw, ok := obj[key]
	if !ok {
		return "", false, nil
	}
	var value string
	if err := json.Unmarshal(raw, &value); err != nil {
		return "", false, statusErr(http.StatusBadRequest, "invalid "+key)
	}
	return value, true, nil
}

func readMultipart(r *http.Request) (inbound, error) {
	reader, err := r.MultipartReader()
	if err != nil {
		return inbound{}, statusErrCause(http.StatusBadRequest, "invalid multipart body", err)
	}
	var in inbound
	seen := map[string]struct{}{}
	for {
		part, err := reader.NextPart()
		if errors.Is(err, io.EOF) {
			return in, nil
		}
		if err != nil {
			if tooLarge(err) {
				return inbound{}, statusErr(http.StatusRequestEntityTooLarge, "request body too large")
			}
			return inbound{}, statusErrCause(http.StatusBadRequest, "invalid multipart body", err)
		}
		if err := readPart(&in, seen, part); err != nil {
			return inbound{}, err
		}
	}
}

func readPart(in *inbound, seen map[string]struct{}, part *multipart.Part) error {
	name := part.FormName()
	data, err := io.ReadAll(part)
	closeErr := part.Close()
	if err != nil {
		if tooLarge(err) {
			return statusErr(http.StatusRequestEntityTooLarge, "request body too large")
		}
		return statusErrCause(http.StatusBadRequest, "invalid multipart body", err)
	}
	if closeErr != nil {
		return statusErrCause(http.StatusBadRequest, "invalid multipart body", closeErr)
	}
	if name == "" {
		return statusErr(http.StatusBadRequest, "missing form field name")
	}
	if _, ok := seen[name]; ok {
		return statusErr(http.StatusBadRequest, "duplicate field")
	}
	seen[name] = struct{}{}
	switch name {
	case "auth_token":
		in.authPresent = true
		in.authToken = string(data)
	case "request_id":
		in.requestIDPresent = true
		in.requestID = string(data)
	case "content":
		in.contentPresent = true
		in.content = string(data)
	case "file":
		file, fileErr := fileFromPart(part, data)
		if fileErr != nil {
			return fileErr
		}
		in.file = file
	default:
		return statusErr(http.StatusBadRequest, "unknown field")
	}
	return nil
}

func fileFromPart(part *multipart.Part, data []byte) (*inboundFile, error) {
	disposition := part.Header.Get("Content-Disposition")
	if disposition == "" {
		return nil, statusErr(http.StatusBadRequest, "missing file content disposition")
	}
	mediaDisp, params, err := mime.ParseMediaType(disposition)
	if err != nil || mediaDisp != "form-data" {
		return nil, statusErr(http.StatusBadRequest, "invalid file content disposition")
	}
	name := params["filename"]
	if err := validateFileName(name); err != nil {
		return nil, err
	}
	rawType := part.Header.Get("Content-Type")
	if rawType == "" {
		return nil, statusErr(http.StatusBadRequest, "missing file content type")
	}
	mediaType, typeParams, err := mime.ParseMediaType(rawType)
	if err != nil {
		return nil, statusErr(http.StatusBadRequest, "invalid file content type")
	}
	formatted := mime.FormatMediaType(mediaType, typeParams)
	if formatted == "" {
		return nil, statusErr(http.StatusBadRequest, "invalid file content type")
	}
	if data == nil {
		data = []byte{}
	}
	return &inboundFile{name: name, mime: formatted, data: data}, nil
}

func validateFileName(name string) error {
	if name == "" || name == "." || name == ".." {
		return statusErr(http.StatusBadRequest, "missing file name")
	}
	if strings.ContainsAny(name, `/\`) || !utf8.ValidString(name) {
		return statusErr(http.StatusBadRequest, "invalid file name")
	}
	for _, r := range name {
		if r < 0x20 || r == 0x7f {
			return statusErr(http.StatusBadRequest, "invalid file name")
		}
	}
	return nil
}

func tooLarge(err error) bool {
	var maxErr *http.MaxBytesError
	return errors.As(err, &maxErr)
}
